def _env_bool(name, default=False):
    """Lee un booleano de entorno con valores explícitos."""
    return os.getenv(name, str(default)).strip().lower() in ('1', 'true', 'yes')


def _env_int(name, default):
    """Lee un entero positivo de entorno, con respaldo seguro."""
    try:
        value = int(os.getenv(name, str(default)))
    except (TypeError, ValueError):
        return default
    return value if value > 0 else default


def _env_nonnegative_int(name, default):
    """Lee un entero mayor o igual a cero; un valor inválido usa el respaldo."""
    try:
        value = int(os.getenv(name, str(default)))
    except (TypeError, ValueError):
        return default
    return value if value >= 0 else default


